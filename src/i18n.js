// ── Current language ──
let _lang = localStorage.getItem(STORAGE_KEY) || 'zh';

// ── Public API ──
export function t(key) {
  const table = I18N[_lang] || I18N.zh;
  return table[key] || I18N.zh[key] || I18N.en[key] || key;
}

// ── 反查字典：硬编码中文文案的运行时翻译 ──
// 中文界面：原文即为中文，直接返回（DICT 不含 zh 条目，避免兜底到英文）
// 其他语言：命中 DICT → 当前语言；未命中 → 英文兜底；再未命中（人名/用户数据）→ 原样返回
export function tr(s) {
  if (s === null || s === undefined) return s;
  if (_lang === 'zh') return s;
  const e = DICT[String(s)];
  if (!e) return s;
  return e[_lang] || e.en || s;
}

export function getLang() {
  return _lang;
}

export function setLang(lang) {
  if (!LANGUAGES[lang]) return;
  _lang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  // Update HTML lang and dir attributes
  const html = document.documentElement;
  html.lang = lang;
  html.dir = LANGUAGES[lang].rtl ? 'rtl' : 'ltr';
  // Apply RTL class to body
  if (LANGUAGES[lang].rtl) {
    document.body.classList.add('rtl');
  } else {
    document.body.classList.remove('rtl');
  }
}

export function initLang() {
  setLang(_lang);
}

// ── Apply translations to DOM elements with data-i18n attribute ──
export function applyTranslations() {
  // Static HTML elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text) el.textContent = text;
  });
  // Placeholder text
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    const text = t(key);
    if (text) el.placeholder = text;
  });
  // 反查字典：data-tr="中文原文" / data-tr-ph="中文占位符"
  document.querySelectorAll('[data-tr]').forEach(el => {
    const text = tr(el.getAttribute('data-tr'));
    if (text) el.textContent = text;
  });
  document.querySelectorAll('[data-tr-ph]').forEach(el => {
    const text = tr(el.getAttribute('data-tr-ph'));
    if (text) el.placeholder = text;
  });
  // title 提示（工具提示）
  document.querySelectorAll('[data-tr-title]').forEach(el => {
    const text = tr(el.getAttribute('data-tr-title'));
    if (text) el.title = text;
  });
}
